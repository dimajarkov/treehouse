package pool

import (
	"fmt"
	"os"
	"path/filepath"
)

// HoldLaunchOwner is the cooperative launch-owner boundary. Every controlled
// launcher, including pre-admission commands/waiters, must hold shared for its
// complete lifetime. Maintenance takes exclusive nonblocking and never kills
// an actor to obtain it. Initial legacy coverage is a separately proven rollout
// prerequisite, not inferred from an empty newly provisioned lock.
func HoldLaunchOwner(pool string, exclusive bool) (func() error, func(), error) {
	canonical, e := filepath.EvalSymlinks(pool)
	if e != nil || !filepath.IsAbs(pool) || canonical != pool {
		return nil, nil, fmt.Errorf("canonical owner pool required")
	}
	path := filepath.Join(pool, "treehouse-launch-owner.lock")
	f, e := openInspectionFile(path)
	if e != nil {
		return nil, nil, fmt.Errorf("existing cooperative owner boundary required")
	}
	info, e := f.Stat()
	if e != nil || info.Mode().Perm() != 0600 {
		f.Close()
		return nil, nil, fmt.Errorf("private owner boundary required")
	}
	id, e := aliasIdentity(path)
	if e != nil {
		f.Close()
		return nil, nil, e
	}
	if exclusive {
		e = tryLockFile(f)
	} else {
		e = trySharedAdmissionLock(f)
	}
	if e != nil {
		f.Close()
		return nil, nil, fmt.Errorf("owned launchers or legacy waiters not drained; wait for voluntary exit")
	}
	closed := false
	release := func() {
		if !closed {
			closed = true
			unlockFile(f)
			f.Close()
		}
	}
	check := func() error {
		if closed {
			return fmt.Errorf("owner maintenance hold lost")
		}
		current, e := aliasIdentity(path)
		if e != nil || current != id {
			return fmt.Errorf("owner boundary replaced")
		}
		held, e := f.Stat()
		named, ne := os.Lstat(path)
		if e != nil || ne != nil || !os.SameFile(held, named) {
			return fmt.Errorf("owner handle lost")
		}
		return nil
	}
	return check, release, nil
}

// BridgePolicy is installed owner policy under the exact pool. It is not
// generated by a command, flag, environment variable or preview. Provisioning
// it is allowed only after the named owner scope and pre-gate drain are proven
// under separate maintenance authority. Unknown/uncontrolled owners block that
// rollout, even when newly created locks would be empty.
type BridgePolicy struct {
	Version string         `json:"version"`
	Pool    string         `json:"pool"`
	Route   AdmissionRoute `json:"route"`
	Owners  []string       `json:"owners"`
}

func ReadBridgePolicy(pool string) (BridgePolicy, func() error, error) {
	var p BridgePolicy
	path := filepath.Join(pool, "treehouse-launch-policy.json")
	bytes, e := readInspectionFile(path, 1<<20)
	if e != nil {
		return p, nil, fmt.Errorf("reviewed launch-owner policy absent; owner scope unknown")
	}
	info, e := os.Lstat(path)
	if e != nil || info.Mode().Perm() != 0600 {
		return p, nil, fmt.Errorf("private installed owner policy required")
	}
	identity, e := aliasIdentity(path)
	if e != nil {
		return p, nil, e
	}
	if e = StrictAliasJSON(bytes, &p); e != nil {
		return p, nil, e
	}
	if p.Version != "treehouse.launch-owner.v1" || p.Pool != pool || len(p.Owners) == 0 {
		return p, nil, fmt.Errorf("unknown launch-owner scope")
	}
	seen := map[string]bool{}
	for _, o := range p.Owners {
		if o == "" || seen[o] {
			return p, nil, fmt.Errorf("ambiguous launch-owner scope")
		}
		seen[o] = true
	}
	check := func() error {
		current, e := aliasIdentity(path)
		if e != nil || current != identity {
			return fmt.Errorf("launch-owner policy identity changed")
		}
		b, e := readInspectionFile(path, 1<<20)
		if e != nil || aliasHash(b) != aliasHash(bytes) {
			return fmt.Errorf("launch-owner policy changed")
		}
		return nil
	}
	return p, check, nil
}

// InheritedLaunchHandles supplies actual shared-lock file descriptions to the
// backing child. Kernel locks survive supervisor death while that child lives.
func InheritedLaunchHandles(pool string) ([]*os.File, error) {
	var files []*os.File
	for _, name := range []string{"treehouse-launch-admission.lock", "treehouse-launch-owner.lock"} {
		f, e := openInspectionFile(filepath.Join(pool, name))
		if e != nil {
			for _, p := range files {
				p.Close()
			}
			return nil, e
		}
		stat, statErr := f.Stat()
		if statErr != nil {
			f.Close()
			for _, p := range files {
				p.Close()
			}
			return nil, statErr
		}
		if _, e = aliasFileIdentity(stat); e != nil {
			f.Close()
			for _, p := range files {
				p.Close()
			}
			return nil, e
		}
		if e = trySharedAdmissionLock(f); e != nil {
			f.Close()
			for _, p := range files {
				p.Close()
			}
			return nil, e
		}
		files = append(files, f)
	}
	return files, nil
}

// VerifyInheritedLaunch checks the named gates against the inherited handles,
// obtains shared locks on those very descriptions and pins the approved route.
// No environment value alone establishes authority; invalid descriptors deny.
func VerifyInheritedLaunch(pool string, route AdmissionRoute, gate, owner *os.File) (func() error, error) {
	for i, name := range []string{"treehouse-launch-admission.lock", "treehouse-launch-owner.lock"} {
		f := []*os.File{gate, owner}[i]
		held, e := f.Stat()
		named, ne := os.Lstat(filepath.Join(pool, name))
		if e != nil || ne != nil || !named.Mode().IsRegular() || named.Mode().Perm() != 0600 || !os.SameFile(held, named) {
			return nil, fmt.Errorf("inherited admission descriptor mismatch")
		}
		if _, e = aliasFileIdentity(held); e != nil {
			return nil, e
		}
		if e = trySharedAdmissionLock(f); e != nil {
			return nil, e
		}
	}
	check, release, e := HoldCommandAdmission(pool, route)
	if e != nil {
		return nil, e
	}
	// This additional handle intentionally remains for command lifetime. Kernel
	// closes it at exit; inherited gate/owner descriptions are independently held.
	_ = release
	return check, nil
}
